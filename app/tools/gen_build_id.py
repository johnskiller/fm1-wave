"""The build's identity: the commit this firmware was made from, as a short string.

    python3 tools/gen_build_id.py build/gen/build_id.h     (build.py's gen step, or by hand)

Why. `build.py` names the package `wave.fwsc` whatever it built, and the image itself
carried no mark, so "which commit is on the device?" could only be answered by
re-flashing and guessing. That cost a whole session: the same screen looked wrong on
the device and right in the emulator, and the emulator was a different commit -- the
comparison was invalid before it started, and every theory built on it was wasted.

Two rules:

1. **It must not change when nothing else did.** The hash is the tree's, not the
   clock's: no date, no time. A rebuild of the same tree produces the same bytes, so
   the debug corner reading "@05b8a62" is a claim about the sources and nothing else.

2. **It must never fail the build.** A tarball has no `.git`; a `git` too old for
   `describe` is not a reason to stop someone building. Fall back to "nogit" and let
   the build through -- an identity that sometimes blocks compilation is worse than
   one that sometimes says "unknown".
"""
import subprocess
import sys
from pathlib import Path


def git(*args):
    r = subprocess.run(["git", *args], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_build_id.py OUT.h")
    out = Path(sys.argv[1])
    app = Path(__file__).resolve().parent.parent

    sha = git("-C", str(app), "rev-parse", "--short=7", "HEAD")
    # a dirty tree is a different firmware with the same name: say so, because the
    # whole point of the mark is that two different images must not look identical
    if sha and git("-C", str(app), "status", "--porcelain", "--untracked-files=no"):
        sha += "+"
    if not sha:
        sha = "nogit"

    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w") as fp:
        fp.write("/* generated by tools/gen_build_id.py: do not edit */\n")
        fp.write("/* the sources this image was built from; %s is a tree with uncommitted edits */\n"
                 % (sha.rstrip("+") + "+" if sha.endswith("+") else "no suffix"))
        fp.write("#pragma once\n\n")
        fp.write('#define APP_BUILD_ID "%s"\n' % sha)
    print("build id: %s" % sha)


if __name__ == "__main__":
    main()
